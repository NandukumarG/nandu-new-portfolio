const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.PORTFOLIO_URL || 'http://127.0.0.1:4173';
(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const errors = [], failed = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
  page.on('response', r => { if (r.status() >= 400) failed.push(`${r.status()} ${r.url()}`); });
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('h1').count(), 1);
  assert.deepEqual(await page.locator('main > section').evaluateAll(els => els.map(el => el.id)), ['top', 'about', 'stack', 'work', 'systems', 'connect']);
  assert.equal(await page.locator('.system-project').count(), 2);
  assert.equal(await page.locator('.tech-category').count(), 5);
  assert.equal(await page.locator('.tech-item').count(), 16);
  assert.equal(await page.locator('.earth-canvas').count(), 0, 'Earth must be deferred at initial load');
  await page.screenshot({ path: 'artifacts/desktop-hero.png' });
  await page.locator('#work').scrollIntoViewIfNeeded();
  await page.getByRole('button', { name: 'Next project', exact: true }).click();
  assert.match(await page.locator('.carousel-index').innerText(), /02.*05/s);
  await page.locator('.carousel-track').focus();
  await page.keyboard.press('ArrowRight');
  assert.match(await page.locator('.carousel-index').innerText(), /03.*05/s);
  await page.keyboard.press('Home');
  assert.match(await page.locator('.carousel-index').innerText(), /01.*05/s);
  await page.getByRole('button', { name: 'UI/UX', exact: true }).click();
  assert.equal(await page.locator('.carousel-card').count(), 2);
  await page.getByRole('button', { name: 'Next project', exact: true }).click();
  const trigger = page.getByRole('button', { name: 'Explore Paper Weight concept', exact: true });
  // Finish the coverflow transition before targeting a control on its moving
  // face; browser hit-testing during perspective interpolation is asynchronous.
  await page.locator('.carousel-card.is-active').evaluate(el => Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished)));
  await trigger.click();
  await page.locator('dialog[open]').waitFor();
  assert.match(await page.locator('#dialog-title').innerText(), /Paper Weight/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog[open]').count(), 0);
  await trigger.waitFor({ state: 'visible' });
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true, 'Dialog must restore focus');
  await page.getByRole('button', { name: 'All', exact: true }).click();
  const stage = page.locator('.carousel-track');
  const box = await stage.boundingBox();
  await page.mouse.move(box.x + box.width * .55, box.y + 110);
  await page.mouse.down(); await page.mouse.move(box.x + box.width * .55 - 150, box.y + 110, { steps: 10 }); await page.mouse.up();
  assert.match(await page.locator('.carousel-index').innerText(), /02.*05/s);
  await page.getByRole('button', { name: 'Let’s Talk', exact: true }).click();
  await page.locator('dialog[open]').waitFor();
  await page.getByLabel('Your name').fill('QA Visitor');
  await page.getByLabel('Email address').fill('qa@example.org');
  await page.getByLabel('What would you like to build?').fill('A focused product interface and a dependable API.');
  await page.getByRole('button', { name: 'Copy project brief', exact: true }).click();
  await page.getByRole('button', { name: 'Brief copied', exact: true }).waitFor();
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /QA Visitor/);
  assert.match(await page.locator('.form-note').innerText(), /Nothing has been sent/);
  await page.keyboard.press('Escape');
  await page.locator('#systems').scrollIntoViewIfNeeded();
  const node = page.locator('.system-node').first(); await node.focus();
  assert.match(await page.locator('.architecture figcaption').first().innerText(), /focused interface/);
  await page.locator('#connect').scrollIntoViewIfNeeded();
  await page.locator('.earth-canvas[data-earth-ready="true"]').waitFor();
  await page.waitForTimeout(300);
  const earthA = await page.locator('.earth-canvas').getAttribute('data-earth-angle');
  await page.waitForTimeout(300);
  assert.notEqual(await page.locator('.earth-canvas').getAttribute('data-earth-angle'), earthA, 'Visible Earth must rotate');
  await page.getByRole('button', { name: 'Pause motion', exact: true }).click();
  const pausedA = await page.locator('.earth-canvas').getAttribute('data-earth-angle');
  await page.waitForTimeout(180);
  assert.equal(await page.locator('.earth-canvas').getAttribute('data-earth-angle'), pausedA, 'Pause motion must stop canvas');
  await page.getByRole('button', { name: 'Resume motion', exact: true }).click();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const reducedA = await page.locator('.earth-canvas').getAttribute('data-earth-angle');
  await page.waitForTimeout(180);
  assert.equal(await page.locator('.earth-canvas').getAttribute('data-earth-angle'), reducedA, 'Reduced motion must stop canvas');
  await page.evaluate(() => { document.activeElement?.blur(); scrollTo(0,0); });
  await page.screenshot({ path: 'artifacts/desktop-full.png', fullPage: true });
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}px`);
    const broken = await page.locator('img').evaluateAll(imgs => imgs.filter(i => i.complete && !i.naturalWidth).map(i => i.src));
    assert.deepEqual(broken, [], `Broken images at ${width}px`);
    const headline = await page.locator('h1 em').boundingBox();
    assert.ok(headline.x + headline.width <= width, `Hero headline must fit at ${width}px`);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  const mobileNav = page.getByRole('dialog', { name: 'Mobile navigation' });
  await mobileNav.waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog[open]').count(), 0);
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await mobileNav.getByRole('link', { name: /Stack/ }).click();
  assert.equal(await page.locator('dialog[open]').count(), 0);
  assert.equal(new URL(page.url()).hash, '#stack');
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({ path: 'artifacts/mobile-hero.png' });
  await page.screenshot({ path: 'artifacts/mobile-full.png', fullPage: true });
  const links = await page.locator('a[href^="#"]').evaluateAll(els => els.map(el => el.getAttribute('href')).filter(href => !document.getElementById(href.slice(1))));
  assert.deepEqual(links, [], 'All internal links must resolve');
  assert.deepEqual(errors, [], 'No console/runtime errors');
  assert.deepEqual(failed, [], 'No failed resource requests');
  // Real touch events exercise browser gesture arbitration, not mouse emulation.
  const touchContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const touch = await touchContext.newPage();
  await touch.goto(base, { waitUntil: 'networkidle' });
  await touch.locator('#work').scrollIntoViewIfNeeded();
  const swipeBox = await touch.locator('.carousel-track').boundingBox();
  const cdp = await touchContext.newCDPSession(touch);
  const startX = 300, y = swipeBox.y + 125;
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: startX, y }] });
  for (let i = 1; i <= 8; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: startX - i * 22, y: y + 2 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.match(await touch.locator('.carousel-index').innerText(), /02.*05/s, 'Touch swipe changes the active card');
  assert.equal(await touch.locator('.cursor').evaluate(el => getComputedStyle(el).display), 'none', 'Custom cursor is disabled for touch');
  await touchContext.close();
  await browser.close();
  console.log('PASS: section order, lazy globe, filters, carousel arrows/keyboard/drag, dialogs/focus, clipboard, architecture, reduced motion, animation pause, navigation, links, images, and widths 320/390/768/1024/1440.');
})().catch(e => { console.error(e); process.exit(1); });
